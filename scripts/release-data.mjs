// The pure half of fetch-release.mjs: reading GitHub's release JSON and turning
// que's generated docs into Starlight pages. No network and no files here, so
// the tests can feed it fixtures.

export const QUE_REPO = 'que-agents/que'

/**
 * @typedef {object} Release
 * @property {string} tag the git tag, e.g. "v0.2.0"
 * @property {string} version the tag without its leading "v"
 * @property {string} publishedAt ISO 8601
 * @property {string} url the release's page on GitHub
 * @property {{ name: string, url: string, size: number }} dmg the Apple Silicon disk image
 */

/**
 * Picks what the site needs from a GitHub "latest release" response.
 * @param {any} json
 * @returns {Release}
 */
export function pickRelease(json) {
  const tag = json?.tag_name
  if (typeof tag !== 'string' || tag === '') {
    throw new Error('the release has no tag_name')
  }
  const assets = Array.isArray(json.assets) ? json.assets : []
  const dmg = assets.find(
    (/** @type {any} */ asset) =>
      typeof asset?.name === 'string' && asset.name.endsWith('-arm64.dmg')
  )
  if (!dmg) {
    throw new Error(`release ${tag} has no asset ending in -arm64.dmg`)
  }

  return {
    tag,
    version: tag.replace(/^v/, ''),
    publishedAt: json.published_at,
    url: json.html_url,
    dmg: { name: dmg.name, url: dmg.browser_download_url, size: dmg.size }
  }
}

/** que's docs that have a page on the site, by their path in que. */
export const SITE_PAGES = /** @type {Record<string, string>} */ ({
  'docs/cli.md': '/reference/cli/',
  'docs/configuration.md': '/reference/configuration/'
})

/**
 * Where a link found in que's file `fromPath` should point on the site: a site
 * page when one exists, else the file on GitHub at the tag (images from raw).
 * Absolute URLs, in-page anchors and root-relative paths are left alone.
 * @param {string} target
 * @param {{ fromPath: string, tag: string, image?: boolean }} options
 */
export function rewriteLink(target, { fromPath, tag, image = false }) {
  if (
    target === '' ||
    target.startsWith('#') ||
    target.startsWith('/') ||
    /^[a-z][a-z0-9+.-]*:/i.test(target)
  ) {
    return target
  }
  const hashAt = target.indexOf('#')
  const pathPart = hashAt === -1 ? target : target.slice(0, hashAt)
  const hash = hashAt === -1 ? '' : target.slice(hashAt)
  const resolved = new URL(pathPart, `https://que.invalid/${fromPath}`).pathname.slice(1)
  const page = SITE_PAGES[resolved]
  if (page && !image) {
    return page + hash
  }
  const base = image
    ? `https://raw.githubusercontent.com/${QUE_REPO}/${tag}/`
    : `https://github.com/${QUE_REPO}/blob/${tag}/`

  return base + resolved + hash
}

// An inline code span (left as it is), or an inline link or image whose label
// may hold code or one level of brackets.
const INLINE = /(`+)[\s\S]*?\1|(!?)\[((?:[^[\]\n]|\[[^\]\n]*\])*)\]\(([^)\s]+)((?:\s+"[^"]*")?)\)/g
// A reference definition, `[label]: target`, but not a footnote.
const REFERENCE = /^( {0,3}\[(?!\^)[^\]\n]+\]:[ \t]*)(\S+)/gm
const FENCE = /^ {0,3}(`{3,}|~{3,})/

/**
 * Rewrites every link target in a Markdown document's prose, leaving fenced
 * code blocks and inline code alone.
 * @param {string} markdown
 * @param {(target: string, image: boolean) => string} fn
 */
export function mapLinks(markdown, fn) {
  /** @param {string} text */
  const prose = (text) =>
    text
      .replace(INLINE, (match, ticks, bang, label, target, title) =>
        ticks ? match : `${bang}[${label}](${fn(target, bang === '!')}${title})`
      )
      .replace(REFERENCE, (_, head, target) => head + fn(target, false))
  /** @type {string[]} */
  const out = []
  /** @type {string[]} */
  let pending = []
  const flush = () => {
    if (pending.length > 0) {
      out.push(prose(pending.join('\n')))
      pending = []
    }
  }
  let fence = ''
  for (const line of markdown.split('\n')) {
    const opener = line.match(FENCE)?.[1]
    if (fence === '' && opener) {
      flush()
      fence = opener
      out.push(line)
    } else if (fence !== '') {
      out.push(line)
      if (line.trim().startsWith(fence) && line.trim().replace(/[`~]/g, '') === '') {
        fence = ''
      }
    } else {
      pending.push(line)
    }
  }
  flush()

  return out.join('\n')
}

/**
 * Turns one of que's generated docs into a Starlight page: frontmatter in,
 * the leading H1 out (Starlight renders the title), the "Generated by … Do not
 * edit by hand" paragraph replaced by a note naming the release, the
 * generated-block comment markers dropped, and relative links pointed at the
 * site or at GitHub.
 * @param {string} markdown
 * @param {{ path: string, title: string, description: string, release: Pick<Release, 'tag' | 'version' | 'url'> }} options
 */
export function transformDoc(markdown, { path, title, description, release }) {
  let body = markdown.replace(/\r\n/g, '\n')
  body = body.replace(/^\s*# [^\n]*\n*/, '')
  body = body.replace(/(^|\n\n)Generated by [\s\S]*?Do not edit[\s\S]*?(?=\n\n|$)/, '$1')
  body = body.replace(/^<!-- \/?generated(?::[\w-]+)? -->\n*/gm, '')
  body = mapLinks(body, (target, image) =>
    rewriteLink(target, { fromPath: path, tag: release.tag, image })
  )
  const frontmatter = [
    '---',
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(description)}`,
    // The page is written at build time; its source is in que, not here.
    'editUrl: false',
    '---'
  ].join('\n')
  const note =
    `_Generated from [que ${release.version}](${release.url}). ` +
    `To change it, edit que's source in [${QUE_REPO}](https://github.com/${QUE_REPO})._`

  return `${frontmatter}\n\n${note}\n\n${body.trim()}\n`
}
